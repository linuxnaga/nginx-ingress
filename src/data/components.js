export const ALL_COMPONENTS = COMPONENT_GROUPS.flatMap((g) => g.items.map((i) => ({ ...i, group: g.id })))

// Map a diagram node id to its reference entry id
export function componentForNode(nodeId) {
  const alias = { workers: 'w1', w2: 'w1', v2: 'v1' }
  const n = alias[nodeId] || nodeId
  return ALL_COMPONENTS.find((c) => c.node === n)?.id
}
