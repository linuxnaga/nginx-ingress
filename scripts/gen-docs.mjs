// Generates docs/LAB_GUIDE.md and docs/COMPONENTS.md from the same data the
// app renders, so the written guide never drifts from the in-app guide.
// Usage: npm run docs
import { writeFileSync, mkdirSync } from 'node:fs'
import { GETTING_STARTED, LAB_GUIDES, MISSION_GUIDES } from '../src/data/guides.js'
import { MODULES, MISSIONS } from '../src/data/curriculum.js'
import { COMPONENT_GROUPS } from '../src/data/components.js'
import { COMMAND_EXAMPLES } from '../src/data/commandExamples.js'

const LABS_BY_MODULE = { m1: ['loop'], m2: ['canary'], m3: ['policy', 'l4'], m4: ['storm', 'metrics', 'migrate'] }
const header = '<!-- Generated by scripts/gen-docs.mjs from src/data/*.js. Edit those files, then run `npm run docs`. -->\n\n'

let g = header + '# Lab Guide\n\n'
g += `## ${GETTING_STARTED.title}\n\n${GETTING_STARTED.intro}\n\n`
GETTING_STARTED.steps.forEach((s, i) => (g += `${i + 1}. **${s.title}.** ${s.body}\n`))
g += '\n'
for (const m of MODULES) {
  g += `---\n\n## Module ${m.num}: ${m.title}\n\n${m.summary.replace(/`/g, '`')}\n\n**Key concepts**\n\n`
  m.concepts.forEach((c) => (g += `- ${c}\n`))
  g += '\n**Objectives (XP)**\n\n'
  m.tasks.forEach((t) => (g += `- ${t.label} (+${t.xp} XP)\n`))
  g += '\n'
  for (const id of LABS_BY_MODULE[m.id]) {
    const l = LAB_GUIDES[id]
    g += `### Lab: ${l.title}\n\n**Goal:** ${l.goal}\n\n**Steps**\n\n`
    l.steps.forEach((s, i) => (g += `${i + 1}. ${s}\n`))
    g += '\n**What to watch**\n\n'
    l.watch.forEach((w) => (g += `- ${w}\n`))
    g += `\n> **Key takeaway:** ${l.takeaway}\n\n`
  }
}
g += '---\n\n## Missions\n\n'
for (const ms of MISSIONS) {
  const mg = MISSION_GUIDES[ms.id]
  g += `### Mission ${ms.num}: ${ms.title} (+${ms.xp} XP)\n\n${ms.brief}\n\n**Objectives**\n\n`
  ms.objectives.forEach((o) => (g += `- [ ] ${o.text}\n`))
  g += '\n**Walkthrough**\n\n'
  mg.steps.forEach((s, i) => (g += `${i + 1}. ${s}\n`))
  g += `\n> **Tip:** ${mg.tips}\n\n`
}

let c = header + '# Component Reference\n\nWhat each part of an F5 NGINX Ingress Controller deployment does, from the Kubernetes objects it watches to the NGINX processes that serve traffic. Every command has a worked example: what to type, sample output from the cafe demo cluster, and what to look for. Sample output is illustrative, so names, IPs and ages will differ in your cluster.\n\n'
c += '```mermaid\nflowchart LR\n'
c += '  dev[Developer / CI] -->|kubectl apply| api[K8s API Server]\n'
c += '  subgraph pod[NIC pod - single container]\n'
c += '    subgraph ic[IC Go process]\n'
c += '      inf[Informers] --> wq[Workqueue] --> ctl[Controller sync] --> cfg[Configurator] --> mgr[Manager]\n'
c += '    end\n'
c += '    mgr -->|write| conf["/etc/nginx/*.conf"]\n'
c += '    conf -->|reload| master[NGINX master]\n'
c += '    mgr -.->|Plus only: no reload| plusapi[NGINX Plus API]\n'
c += '    master --> workers[NGINX workers]\n'
c += '    plusapi -.-> workers\n'
c += '  end\n'
c += '  api -->|watch events| inf\n'
c += '  client[External client] --> lb[Cloud LB / NodePort] --> workers\n'
c += '  workers -->|pod IPs from EndpointSlices| pods[Backend pods v1 / v2]\n'
c += '```\n\n'
c += '**Contents**\n\n'
COMPONENT_GROUPS.forEach((grp) => {
  c += `- ${grp.title}\n`
  grp.items.forEach((i) => (c += `  - [${i.name}](#${i.id})\n`))
})
c += '\n'
for (const grp of COMPONENT_GROUPS) {
  c += `## ${grp.title}\n\n${grp.intro}\n\n`
  for (const i of grp.items) {
    c += `<a id="${i.id}"></a>\n\n### ${i.name}\n\n${i.what}\n\n${i.how}\n\n`
    c += `| | |\n|---|---|\n| **In** | ${i.inputs} |\n| **Out** | ${i.outputs} |\n\n`
    c += '**Commands** (expand for a worked example)\n\n'
    for (const cmd of i.commands) {
      const ex = COMMAND_EXAMPLES[cmd]
      if (!ex) { c += '```bash\n' + cmd + '\n```\n\n'; continue }
      c += `<details>\n<summary><code>${cmd.replace(/</g, '&lt;').replace(/>/g, '&gt;')}</code></summary>\n\n`
      c += '```bash\n$ ' + ex.run + '\n```\n\nSample output:\n\n```text\n' + ex.output + '\n```\n\n'
      c += `**What to look for:** ${ex.look}\n\n</details>\n\n`
    }
  }
}

mkdirSync('docs', { recursive: true })
writeFileSync('docs/LAB_GUIDE.md', g)
writeFileSync('docs/COMPONENTS.md', c)
console.log('wrote docs/LAB_GUIDE.md and docs/COMPONENTS.md')
